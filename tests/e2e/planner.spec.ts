import { test, expect, goto, saveDialog, readWorkspace, confirmDelete } from './helpers'

test('planner CRUD, filters, calendar views, recurrence and refresh persistence', async ({ page }) => {
  await goto(page, '/planner')
  await page.locator('.page-heading-action button').click()
  let dialog = page.getByRole('dialog')
  await dialog.getByLabel('Title', { exact: true }).fill('Team review')
  await dialog.getByLabel('Description', { exact: true }).fill('Review the next milestone')
  await dialog.getByLabel('Category', { exact: true }).selectOption('work')
  await dialog.getByLabel('Priority', { exact: true }).selectOption('high')
  await dialog.getByLabel('Due date', { exact: true }).fill('2026-10-31')
  await dialog.getByLabel('Repeat', { exact: true }).selectOption('daily')
  await dialog.getByLabel('Notes', { exact: true }).fill('Bring the timeline')
  await saveDialog(page, 'Add to my planner')
  await expect(page.getByTestId('task-row')).toContainText('Overdue')
  await page.getByRole('button', { name: 'Edit: Team review', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Title', { exact: true }).fill('Team review updated')
  await saveDialog(page, 'Save changes')
  await page.getByRole('searchbox', { name: 'Find a task…' }).fill('timeline')
  await expect(page.getByTestId('task-row')).toHaveCount(1)
  await page.getByRole('searchbox', { name: 'Find a task…' }).fill('unmatched')
  await expect(page.getByText('Nothing matches your search')).toBeVisible()
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click()
  await page.getByRole('button', { name: 'Mark complete: Team review updated', exact: true }).click()
  await expect.poll(async () => (await readWorkspace(page)).tasks.length).toBe(2)
  let data = await readWorkspace(page)
  expect(data.tasks.filter(task => task.completedAt)).toHaveLength(1)
  expect(data.tasks.find(task => !task.completedAt)?.dueDate).toBe('2026-11-02')
  await page.getByLabel('Status', { exact: true }).selectOption('all')
  await page.getByRole('button', { name: 'Mark incomplete: Team review updated', exact: true }).click()
  await expect(page.getByTestId('task-row')).toHaveCount(2)
  await page.getByTestId('task-row').filter({ hasText: '31 Oct 2026' }).getByRole('button', { name: 'Mark complete: Team review updated', exact: true }).click()
  await expect.poll(async () => (await readWorkspace(page)).tasks.length).toBe(2)
  await page.getByLabel('Status', { exact: true }).selectOption('pending')
  await page.getByRole('tab', { name: 'Month', exact: true }).click()
  await expect(page.locator('.calendar-grid')).toBeVisible()
  await page.getByRole('tab', { name: 'Week', exact: true }).click()
  await page.getByLabel('Date', { exact: true }).fill('2026-11-02')
  await expect(page.locator('.calendar-item')).toContainText('Team review updated')
  await page.getByRole('tab', { name: 'Day', exact: true }).click()
  await expect(page.getByTestId('task-row')).toContainText('Team review updated')
  await page.reload()
  await expect(page.getByTestId('task-row')).toContainText('Team review updated')
  data = await readWorkspace(page)
  expect(data.tasks).toHaveLength(2)
  expect(data.tasks[0].notes).toBe('Bring the timeline')
  await page.getByLabel('Status', { exact: true }).selectOption('all')
  for (let index = 0; index < 2; index++) {
    await page.getByRole('button', { name: 'Delete: Team review updated', exact: true }).first().click()
    await confirmDelete(page)
  }
  expect((await readWorkspace(page)).tasks).toHaveLength(0)
})

test('appointments, routines and invalid input are real planner workflows', async ({ page }) => {
  await goto(page, '/planner')
  await page.locator('.page-heading-action button').click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Title', { exact: true }).fill('   ')
  await dialog.getByRole('button', { name: 'Add to my planner', exact: true }).click()
  await expect(dialog.getByRole('alert')).toBeVisible()
  await dialog.getByLabel('Title', { exact: true }).fill('Project appointment')
  await dialog.getByLabel('Item type', { exact: true }).selectOption('appointment')
  await dialog.getByRole('button', { name: 'Add to my planner', exact: true }).click()
  expect(await dialog.getByLabel('Time', { exact: true }).evaluate(input => (input as HTMLInputElement).validity.valueMissing)).toBe(true)
  await dialog.getByLabel('Time', { exact: true }).fill('14:30')
  await saveDialog(page, 'Add to my planner')
  await expect(page.getByTestId('task-row')).toContainText('Appointment')
  await page.locator('.page-heading-action button').click()
  await page.getByRole('dialog').getByLabel('Title', { exact: true }).fill('Morning routine')
  await page.getByRole('dialog').getByLabel('Item type', { exact: true }).selectOption('routine')
  await expect(page.getByRole('dialog').getByLabel('Repeat', { exact: true })).toHaveValue('daily')
  await saveDialog(page, 'Add to my planner')
  await page.getByRole('button', { name: 'Mark complete: Morning routine', exact: true }).click()
  await expect.poll(async () => (await readWorkspace(page)).tasks.length).toBe(3)
})
