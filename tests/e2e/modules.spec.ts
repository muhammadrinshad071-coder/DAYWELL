import { test, expect, goto, saveDialog, confirmDelete, cancelDialog, readWorkspace } from './helpers'
import { TODAY } from '../fixtures'

test('reminders support due views, notes, editing, recurrence and completed history', async ({ page }) => {
  await goto(page, '/reminders')
  await page.locator('.page-heading-action button').click()
  let dialog = page.getByRole('dialog')
  await dialog.getByLabel('Title', { exact: true }).fill('Energy bill')
  await dialog.getByLabel('Category', { exact: true }).selectOption('bills')
  await dialog.getByLabel('Date', { exact: true }).fill(TODAY)
  await dialog.getByLabel('Time', { exact: true }).fill('09:00')
  await dialog.getByLabel('Repeat', { exact: true }).selectOption('monthly')
  await dialog.getByLabel('Description', { exact: true }).fill('Pay the household bill')
  await dialog.getByLabel('Notes', { exact: true }).fill('Bank reference 204')
  await saveDialog(page, 'Set reminder')
  await expect(page.locator('.stat-value')).toHaveText(['0', '1', '0'])
  await page.getByRole('tab', { name: 'Due & overdue', exact: true }).click()
  await expect(page.getByTestId('reminder-row')).toContainText('Energy bill')
  await page.getByRole('button', { name: 'Edit: Energy bill', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Title', { exact: true }).fill('Energy bill updated')
  await saveDialog(page, 'Save changes')
  await page.getByRole('searchbox', { name: 'Find a reminder…' }).fill('reference 204')
  await expect(page.getByTestId('reminder-row')).toHaveCount(1)
  await page.getByRole('searchbox', { name: 'Find a reminder…' }).fill('unmatched')
  await expect(page.getByText('Nothing matches your search')).toBeVisible()
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click()
  await page.getByRole('button', { name: 'Mark complete: Energy bill updated', exact: true }).click()
  await expect(page.locator('.stat-value')).toHaveText(['1', '0', '1'])
  let data = await readWorkspace(page)
  expect(data.reminders).toHaveLength(2)
  expect(data.reminders.find(record => !record.completedAt)?.date).toBe('2026-12-01')
  await page.getByRole('tab', { name: 'Completed history', exact: true }).click()
  await expect(page.getByTestId('reminder-row')).toContainText('Completed 1 Nov 2026')
  await page.getByRole('button', { name: 'Mark incomplete: Energy bill updated', exact: true }).click()
  await page.getByRole('tab', { name: 'Due & overdue', exact: true }).click()
  await page.getByRole('button', { name: 'Mark complete: Energy bill updated', exact: true }).click()
  await expect.poll(async () => (await readWorkspace(page)).reminders.length).toBe(2)
  await page.getByRole('tab', { name: 'Completed history', exact: true }).click()
  await page.getByRole('button', { name: 'Delete: Energy bill updated', exact: true }).click()
  await confirmDelete(page)
  await page.getByRole('tab', { name: 'Upcoming', exact: true }).click()
  await page.reload()
  await expect(page.getByTestId('reminder-row')).toContainText('Energy bill updated')
  data = await readWorkspace(page)
  expect(data.reminders[0].notes).toBe('Bank reference 204')
  await page.getByRole('button', { name: 'Delete: Energy bill updated', exact: true }).click()
  await confirmDelete(page)
  expect((await readWorkspace(page)).reminders).toHaveLength(0)
})

test('document expiry, renewal, filters and automatic reminder links use saved metadata', async ({ page }) => {
  test.setTimeout(60000)
  await goto(page, '/documents')
  for (const record of [
    { name: 'Vehicle policy', issue: '2025-01-01', expiry: '2026-10-31', notes: 'Annual cover' },
    { name: 'Home policy', issue: '2026-01-01', expiry: '2026-11-20', notes: 'Renewal reference 15' },
    { name: 'Family certificate', issue: '', expiry: '', notes: 'Keep a private copy' },
  ]) {
    await page.locator('.page-heading-action button').click()
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('Name', { exact: true }).fill(record.name)
    await dialog.getByLabel('Category', { exact: true }).selectOption('insurance')
    await dialog.getByLabel('Issue date', { exact: true }).fill(record.issue)
    await dialog.getByLabel('Expiry date', { exact: true }).fill(record.expiry)
    await dialog.getByLabel('Notes', { exact: true }).fill(record.notes)
    await saveDialog(page, 'Save document')
  }
  await expect(page.locator('.stat-value')).toHaveText(['3', '2', '0'])
  await page.getByLabel('Status', { exact: true }).selectOption('renewSoon')
  await expect(page.locator('.document-card')).toHaveCount(1)
  await expect(page.locator('.document-card')).toContainText('Home policy')
  await page.getByRole('searchbox', { name: 'Find a document…' }).fill('reference 15')
  await expect(page.locator('.document-card')).toHaveCount(1)
  await page.getByRole('searchbox', { name: 'Find a document…' }).fill('unmatched')
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click()
  const vehicle = page.locator('.document-card').filter({ has: page.getByRole('heading', { name: 'Vehicle policy', exact: true }) })
  await vehicle.getByRole('button', { name: 'Update renewal', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Expiry date', { exact: true }).fill('2024-01-01')
  await dialog.getByRole('button', { name: 'Save changes', exact: true }).click()
  expect(await dialog.getByLabel('Expiry date', { exact: true }).evaluate(input => (input as HTMLInputElement).validity.rangeUnderflow)).toBe(true)
  await dialog.getByLabel('Expiry date', { exact: true }).fill('2027-10-31')
  await saveDialog(page, 'Save changes')
  await expect(vehicle).toContainText('Up to date')
  await expect(page.locator('.stat-value')).toHaveText(['3', '1', '1'])
  await goto(page, '/reminders')
  await expect(page.locator('.document-mini')).toHaveCount(1)
  await page.locator('.document-mini').click()
  await expect(page.getByRole('dialog').getByLabel('Name', { exact: true })).toHaveValue('Home policy')
  await cancelDialog(page)
  await page.getByRole('button', { name: 'Actions: Home policy', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Delete', exact: true }).click()
  await confirmDelete(page)
  await expect(page.locator('.stat-value')).toHaveText(['2', '0', '1'])
  await page.getByLabel('Status', { exact: true }).selectOption('noExpiry')
  await expect(page.locator('.document-card')).toContainText('Family certificate')
  await page.reload()
  const data = await readWorkspace(page)
  expect(data.documents).toHaveLength(2)
  expect(data.documents.find(record => record.name === 'Vehicle policy')?.expiryDate).toBe('2027-10-31')
  await goto(page, '/reminders')
  await expect(page.locator('.document-mini')).toHaveCount(0)
})

test('shopping totals respect quantity and zero actual prices, and reusable copies preserve history', async ({ page }) => {
  test.setTimeout(60000)
  await goto(page, '/shopping')
  await page.locator('.page-heading-action button').click()
  await page.getByRole('dialog').getByLabel('Name', { exact: true }).fill('Weekly essentials')
  await page.getByRole('dialog').getByRole('checkbox').check()
  await saveDialog(page, 'Create list')
  for (const item of [
    { name: 'Brown rice', quantity: '2', estimate: '51.25', actual: '49.75' },
    { name: 'Milk', quantity: '1.5', estimate: '30', actual: '' },
  ]) {
    await page.locator('.table-card-heading').getByRole('button', { name: 'Add item', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('Item name', { exact: true }).fill(item.name)
    await dialog.getByLabel('Quantity', { exact: true }).fill(item.quantity)
    await dialog.getByLabel('Estimated unit price', { exact: true }).fill(item.estimate)
    await dialog.getByLabel('Actual unit price', { exact: true }).fill(item.actual)
    await saveDialog(page, 'Add item')
  }
  await expect(page.locator('.shopping-summary strong')).toHaveText(['₹147.50', '₹99.50', '₹144.50'])
  await expect(page.getByRole('button', { name: 'Finish this shop', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Edit: Milk', exact: true }).click()
  await page.getByRole('dialog').getByLabel('Quantity', { exact: true }).fill('2')
  await page.getByRole('dialog').getByLabel('Actual unit price', { exact: true }).fill('0')
  await saveDialog(page, 'Save changes')
  await expect(page.locator('.shopping-summary strong')).toHaveText(['₹162.50', '₹99.50', '₹99.50'])
  await page.getByRole('button', { name: 'Actions: Weekly essentials', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Edit', exact: true }).click()
  await expect(page.getByRole('dialog').getByLabel('Currency', { exact: true })).toBeDisabled()
  await page.getByRole('dialog').getByLabel('Name', { exact: true }).fill('Weekly essentials updated')
  await saveDialog(page, 'Save changes')
  for (const name of ['Brown rice', 'Milk']) await page.getByRole('button', { name: `Mark complete: ${name}`, exact: true }).click()
  await expect(page.getByRole('progressbar')).toHaveAttribute('aria-valuenow', '100')
  await page.getByRole('button', { name: 'Finish this shop', exact: true }).click()
  await confirmDelete(page, 'Finish this shop')
  await expect(page.getByRole('tab', { name: 'History', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('button', { name: 'Edit: Milk', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Use again', exact: true }).click()
  await expect(page.getByRole('progressbar')).toHaveAttribute('aria-valuenow', '0')
  await expect(page.locator('.shopping-summary strong')).toHaveText(['₹162.50', '₹0.00', '₹162.50'])
  let data = await readWorkspace(page)
  expect(data.shoppingLists).toHaveLength(2)
  const original = data.shoppingLists.find(record => record.archivedAt)!
  expect(original.items.every(item => item.checked)).toBe(true)
  expect(original.items.find(item => item.name === 'Milk')?.actualPrice).toBe(0)
  expect(data.shoppingLists.find(record => !record.archivedAt)?.items.every(item => !item.checked && item.actualPrice === undefined)).toBe(true)
  await page.locator('.page-heading-action button').click()
  await page.getByRole('dialog').getByLabel('Name', { exact: true }).fill('Travel kit')
  await saveDialog(page, 'Create list')
  await page.getByRole('searchbox', { name: 'Find a list or item…' }).fill('Brown rice')
  await expect(page.locator('.shopping-list-buttons > button')).toHaveCount(1)
  await page.getByRole('button', { name: 'Delete: Milk', exact: true }).click()
  await confirmDelete(page)
  await expect(page.getByTestId('shopping-item')).toHaveCount(1)
  await page.getByRole('button', { name: 'Actions: Weekly essentials updated (copy)', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Delete', exact: true }).click()
  await confirmDelete(page)
  await page.getByRole('searchbox', { name: 'Find a list or item…' }).fill('')
  await expect(page.locator('.shopping-list-buttons > button')).toContainText('Travel kit')
  await page.reload()
  data = await readWorkspace(page)
  expect(data.shoppingLists).toHaveLength(2)
  expect(data.shoppingLists.find(record => record.id === original.id)).toEqual(original)
})

