import { parseBackup } from '../../src/core/backup'
import { samplePdf } from '../file-fixtures'
import { test, expect, goto, saveDialog, readWorkspace, cancelDialog, confirmDelete, dismissToasts } from './helpers'

test('saved services and emergency contacts support CRUD, search, filters and phone/map links', async ({ page }) => {
  test.setTimeout(90000)
  await goto(page, '/local?new=1')
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Name', { exact: true }).fill('Community clinic')
  await dialog.getByLabel('Category', { exact: true }).fill('Healthcare')
  await dialog.getByLabel('Phone number', { exact: true }).fill('+91 (90000) 00000')
  await dialog.getByLabel('Address', { exact: true }).fill('Example Road, Kochi')
  await dialog.getByLabel('Notes', { exact: true }).fill('Reception reference 204')
  await dialog.getByRole('checkbox', { name: 'Emergency contact', exact: true }).check()
  await saveDialog(page, 'Save contact')
  let card = page.locator('.contact-card').filter({ hasText: 'Community clinic' })
  await expect(card).toContainText('Emergency contact')
  await expect(card.getByRole('link', { name: 'Call: Community clinic', exact: true })).toHaveAttribute('href', 'tel:+919000000000')
  const maps = card.getByRole('link', { name: 'Map: Community clinic', exact: true })
  expect(new URL((await maps.getAttribute('href'))!).searchParams.get('query')).toBe('Example Road, Kochi')
  await expect(maps).toHaveAttribute('rel', 'noopener noreferrer')
  await page.getByRole('button', { name: 'Add contact', exact: true }).click()
  await dialog.getByLabel('Name', { exact: true }).fill('Repair desk')
  await dialog.getByLabel('Category', { exact: true }).fill('Home repairs')
  await dialog.getByLabel('Address', { exact: true }).fill('Community centre')
  await saveDialog(page, 'Save contact')
  await expect(page.locator('.contact-card').first()).toContainText('Community clinic')
  await page.getByRole('checkbox', { name: 'Emergency only', exact: true }).check()
  await expect(page.locator('.contact-card')).toHaveCount(1)
  await page.getByRole('checkbox', { name: 'Emergency only', exact: true }).uncheck()
  await page.getByLabel('Contact category', { exact: true }).selectOption('Home repairs')
  await expect(page.locator('.contact-card')).toContainText('Repair desk')
  await page.getByLabel('Contact category', { exact: true }).selectOption('')
  await page.getByRole('searchbox', { name: 'Find a contact or service…', exact: true }).fill('reference 204')
  await expect(page.locator('.contact-card')).toHaveCount(1)
  await card.getByRole('button', { name: 'Edit: Community clinic', exact: true }).click()
  await dialog.getByLabel('Name', { exact: true }).fill('Community clinic updated')
  await dialog.getByLabel('Phone number', { exact: true }).fill('javascript:123')
  await dialog.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(dialog.getByRole('alert')).toBeVisible()
  await dialog.getByLabel('Phone number', { exact: true }).fill('112')
  await saveDialog(page, 'Save changes')
  await page.reload()
  await expect(page.locator('.contact-card')).toHaveCount(2)
  await page.keyboard.press('Control+k')
  await page.getByRole('dialog').getByRole('searchbox').fill('reference 204')
  await page.locator('.search-result').click()
  await expect(dialog.getByLabel('Name', { exact: true })).toHaveValue('Community clinic updated')
  await cancelDialog(page)
  card = page.locator('.contact-card').filter({ hasText: 'Community clinic updated' })
  await card.getByRole('button', { name: 'Actions: Community clinic updated', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Delete', exact: true }).click()
  await confirmDelete(page)
  expect((await readWorkspace(page)).contacts.map(contact => contact.name)).toEqual(['Repair desk'])
})

test('document files validate, persist, download byte-for-byte, replace and remove', async ({ page, context }) => {
  test.setTimeout(90000)
  await goto(page, '/documents?new=1')
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Name', { exact: true }).fill('Household policy')
  const upload = dialog.getByLabel('Document file', { exact: true })
  await upload.setInputFiles({ name: 'fake.pdf', mimeType: 'application/pdf', buffer: Buffer.from('<html>not a PDF</html>') })
  await expect(dialog.getByRole('alert')).toContainText('supported document')
  const original = samplePdf()
  await upload.setInputFiles({ name: 'household-policy.pdf', mimeType: 'application/pdf', buffer: original })
  await expect(dialog.locator('.attachment-summary')).toContainText('household-policy.pdf')
  await saveDialog(page, 'Save document')
  await page.reload()
  const card = page.locator('.document-card')
  await expect(card).toContainText('household-policy.pdf')
  const downloadEvent = page.waitForEvent('download')
  await card.getByRole('button', { name: 'Download file: Household policy', exact: true }).click()
  const download = await downloadEvent
  expect(download.suggestedFilename()).toBe('household-policy.pdf')
  const chunks: Buffer[] = []
  for await (const chunk of await download.createReadStream()) chunks.push(Buffer.from(chunk))
  expect(Buffer.concat(chunks)).toEqual(original)
  await card.getByRole('button', { name: 'Edit', exact: true }).click()
  await dialog.getByRole('button', { name: 'Remove file', exact: true }).click()
  await cancelDialog(page)
  expect((await readWorkspace(page)).documents[0].attachment?.data).toBe(original.toString('base64'))
  await card.getByRole('button', { name: 'Edit', exact: true }).click()
  const replacement = samplePdf('Renewed local policy')
  await upload.setInputFiles({ name: 'renewed-policy.pdf', mimeType: 'application/pdf', buffer: replacement })
  await expect(dialog.locator('.attachment-summary')).toContainText('renewed-policy.pdf')
  await saveDialog(page, 'Save changes')
  expect((await readWorkspace(page)).documents[0].attachment?.data).toBe(replacement.toString('base64'))
  // Wait for a controlling service worker before testing offline reloads.
  await page.evaluate(async () => {
    await navigator.serviceWorker.ready
    if (!navigator.serviceWorker.controller) await new Promise<void>(resolve => navigator.serviceWorker.addEventListener('controllerchange', () => resolve(), { once: true }))
  })
  await context.setOffline(true)
  await page.reload()
  await expect(card).toContainText('renewed-policy.pdf')
  await card.getByRole('button', { name: 'Edit', exact: true }).click()
  await dialog.getByRole('button', { name: 'Remove file', exact: true }).click()
  await saveDialog(page, 'Save changes')
  await page.reload()
  await expect(card.getByRole('button', { name: /^Download file:/ })).toHaveCount(0)
  expect((await readWorkspace(page)).documents[0].attachment).toBeUndefined()
  await context.setOffline(false)
})

test('contacts and attached files survive export, reset, restore and offline contact edits', async ({ page, context }) => {
  test.setTimeout(90000)
  await goto(page, '/local?new=1')
  await page.getByRole('dialog').getByLabel('Name', { exact: true }).fill('Trusted neighbour')
  await page.getByRole('dialog').getByLabel('Phone number', { exact: true }).fill('+91 90000 00000')
  await saveDialog(page, 'Save contact')
  await goto(page, '/documents?new=1')
  await page.getByRole('dialog').getByLabel('Name', { exact: true }).fill('Backup document')
  await page.getByRole('dialog').getByLabel('Document file', { exact: true }).setInputFiles({ name: 'backup.pdf', mimeType: 'application/pdf', buffer: samplePdf() })
  await expect(page.getByRole('dialog').locator('.attachment-summary')).toBeVisible()
  await saveDialog(page, 'Save document')
  const saved = await readWorkspace(page)
  await goto(page, '/settings')
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export backup', exact: true }).click()
  const chunks: Buffer[] = []
  for await (const chunk of await (await downloadEvent).createReadStream()) chunks.push(Buffer.from(chunk))
  const backup = Buffer.concat(chunks)
  expect(parseBackup(backup.toString('utf8')).data).toEqual(saved)
  await page.getByRole('button', { name: 'Delete all local records', exact: true }).click()
  await confirmDelete(page, 'Delete all local records')
  await expect.poll(async () => (await readWorkspace(page)).documents.length).toBe(0)
  expect((await readWorkspace(page)).contacts).toEqual([])
  await page.locator('input[type="file"]').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: backup })
  await confirmDelete(page, 'Replace & restore')
  await expect.poll(() => readWorkspace(page)).toEqual(saved)
  await dismissToasts(page)
  const invalid = JSON.parse(backup.toString('utf8'))
  invalid.data.documents[0].attachment.data = 'corrupt'
  await page.locator('input[type="file"]').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(invalid)) })
  await expect(page.getByRole('alert')).toContainText('not a valid Daywell backup')
  expect(await readWorkspace(page)).toEqual(saved)
  await goto(page, '/local')
  await page.evaluate(async () => {
    await navigator.serviceWorker.ready
    if (!navigator.serviceWorker.controller) await new Promise<void>(resolve => navigator.serviceWorker.addEventListener('controllerchange', () => resolve(), { once: true }))
  })
  await context.setOffline(true)
  await page.reload()
  await expect(page.locator('.contact-card')).toContainText('Trusted neighbour')
  await page.getByRole('button', { name: 'Edit: Trusted neighbour', exact: true }).click()
  await page.getByRole('dialog').getByLabel('Notes', { exact: true }).fill('Updated offline')
  await saveDialog(page, 'Save changes')
  await page.reload()
  await expect(page.locator('.contact-card')).toContainText('Updated offline')
  await context.setOffline(false)
})
