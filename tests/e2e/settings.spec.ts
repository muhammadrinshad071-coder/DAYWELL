import { createBackup, MAX_BACKUP_BYTES, parseBackup } from '../../src/core/backup'
import { emptyWorkspace, preferencesSchema } from '../../src/core/models'
import { populatedWorkspace, TODAY } from '../fixtures'
import { test, expect, goto, restoreViaUI, readWorkspace, addTask, cancelDialog, confirmDelete, dismissToasts, saveDialog } from './helpers'

test('profile, date, language and device-theme preferences persist without changing records', async ({ page }) => {
  const data = populatedWorkspace()
  await restoreViaUI(page, data)
  await page.getByLabel('What should we call you?', { exact: true }).fill('Devika')
  await page.getByLabel('Date format', { exact: true }).selectOption('iso')
  await page.getByLabel('Currency', { exact: true }).selectOption('JPY')
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await page.locator('.theme-options').getByRole('button', { name: 'Follow device', exact: true }).click()
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(page.locator('html')).toHaveClass('dark')
  await expect(page.locator('.topbar-actions').getByRole('button', { name: 'Light', exact: true })).toBeVisible()
  await page.emulateMedia({ colorScheme: 'light' })
  await expect(page.locator('html')).not.toHaveClass('dark')
  await page.locator('.theme-options').getByRole('button', { name: 'Dark', exact: true }).click()
  await page.getByLabel('Language', { exact: true }).selectOption('hi')
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('lang', 'hi')
  await expect(page.locator('.sidebar').getByRole('link', { name: 'दैनिक योजनाकार', exact: true })).toBeVisible()
  await expect(page.getByText('English is complete. Malayalam and Hindi are translation-ready previews', { exact: false })).toBeVisible()
  await page.getByLabel('Language', { exact: true }).selectOption('en')
  await page.getByRole('button', { name: 'सहेजें', exact: true }).click()
  await page.reload()
  await expect(page.getByLabel('What should we call you?', { exact: true })).toHaveValue('Devika')
  await expect(page.getByLabel('Currency', { exact: true })).toHaveValue('JPY')
  await expect(page.locator('html')).toHaveClass('dark')
  await goto(page)
  await expect(page.locator('main h1')).toHaveText('Good morning, Devika.')
  await goto(page, '/planner')
  await expect(page.getByTestId('task-row')).toContainText(TODAY)
  expect(await readWorkspace(page)).toEqual(data)
})

test('a downloaded backup round-trips all records, confirms replacement and keeps preferences on reset', async ({ page }) => {
  test.setTimeout(60000)
  const original = populatedWorkspace()
  const preferences = preferencesSchema.parse({ name: 'Asha', widgets: ['habits', 'tasks', 'spending'] })
  await restoreViaUI(page, original, preferences)
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export backup', exact: true }).click()
  const download = await downloadEvent
  expect(download.suggestedFilename()).toBe(`daywell-backup-${TODAY}.json`)
  const stream = await download.createReadStream()
  const chunks: Buffer[] = []
  for await (const chunk of stream) chunks.push(Buffer.from(chunk))
  const contents = Buffer.concat(chunks)
  const backup = parseBackup(contents.toString('utf8'))
  expect(backup.data).toEqual(original)
  expect(backup.preferences).toEqual(preferences)
  await goto(page, '/planner')
  await addTask(page, 'Added after export')
  await goto(page, '/settings')
  const upload = () => page.locator('input[type="file"]').setInputFiles({ name: 'exported.json', mimeType: 'application/json', buffer: contents })
  await upload()
  await cancelDialog(page)
  expect((await readWorkspace(page)).tasks).toHaveLength(2)
  await upload()
  await confirmDelete(page, 'Replace & restore')
  await expect(page.getByText('Backup restored on this device', { exact: true }).first()).toBeVisible()
  await expect.poll(async () => (await readWorkspace(page)).tasks.length).toBe(1)
  expect(await readWorkspace(page)).toEqual(original)
  await page.getByRole('button', { name: 'Delete all local records', exact: true }).click()
  await cancelDialog(page)
  expect(await readWorkspace(page)).toEqual(original)
  await page.getByRole('button', { name: 'Delete all local records', exact: true }).click()
  await confirmDelete(page, 'Delete all local records')
  await expect(page.getByText('Your local workspace has been cleared', { exact: true })).toBeVisible()
  expect(await readWorkspace(page)).toEqual(emptyWorkspace())
  await page.reload()
  await expect(page.getByLabel('What should we call you?', { exact: true })).toHaveValue('Asha')
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('daywell.preferences')!).widgets)).toEqual(preferences.widgets)
})

test('invalid, incompatible and oversized backup files leave the whole workspace intact', async ({ page }) => {
  const original = populatedWorkspace()
  await restoreViaUI(page, original)
  await dismissToasts(page)
  const unknownVersion = JSON.parse(createBackup(original, preferencesSchema.parse({})))
  unknownVersion.version = 2
  const brokenReference = JSON.parse(createBackup(original, preferencesSchema.parse({})))
  brokenReference.data.habitLogs[0].habitId = crypto.randomUUID()
  for (const contents of ['{invalid', JSON.stringify(unknownVersion), JSON.stringify(brokenReference)]) {
    await page.locator('input[type="file"]').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from(contents) })
    await expect(page.getByRole('alert')).toContainText('This is not a valid Daywell backup. No records were changed.')
    await expect(page.getByRole('dialog')).toHaveCount(0)
    expect(await readWorkspace(page)).toEqual(original)
    await dismissToasts(page)
  }
  await page.locator('input[type="file"]').setInputFiles({ name: 'too-large.json', mimeType: 'application/json', buffer: Buffer.alloc(MAX_BACKUP_BYTES + 1, ' ') })
  await expect(page.getByRole('alert')).toContainText('The backup exceeds the 10 MB import limit. No records were changed.')
  expect(await readWorkspace(page)).toEqual(original)
  await expect(page.getByRole('button', { name: 'Import & restore', exact: true })).toBeEnabled()
})

for (const supported of [true, false]) {
  test(supported ? 'denied notification permission keeps reminders usable and notifications disabled' : 'unsupported notification APIs have an honest fallback', async ({ page, context }) => {
    await context.grantPermissions([])
    if (!supported) await page.addInitScript(() => { Reflect.deleteProperty(window, 'Notification') })
    await goto(page, '/settings')
    if (supported) {
      await expect(page.getByText('Permission blocked', { exact: true })).toBeVisible()
      await page.getByRole('button', { name: 'Enable notifications', exact: true }).click()
      await expect(page.getByRole('button', { name: 'Enable notifications', exact: true })).toBeEnabled()
      expect(await page.evaluate(() => JSON.parse(localStorage.getItem('daywell.preferences')!).notifications)).toBe(false)
    } else {
      await expect(page.getByText('Notifications are not supported in this browser.', { exact: true })).toBeVisible()
      await expect(page.getByRole('button', { name: 'Enable notifications', exact: true })).toHaveCount(0)
    }
    await goto(page, '/reminders')
    await page.locator('.page-heading-action button').click()
    await page.getByRole('dialog').getByLabel('Title', { exact: true }).fill('A reminder without notifications')
    await saveDialog(page, 'Set reminder')
    expect((await readWorkspace(page)).reminders).toHaveLength(1)
  })
}
