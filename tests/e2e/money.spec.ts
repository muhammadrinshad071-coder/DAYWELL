import { test, expect, goto, addTransaction, saveDialog, confirmDelete, readWorkspace } from './helpers'

test('transactions calculate accurate periods, support editing, and never mix currencies', async ({ page }) => {
  await goto(page, '/money')
  await addTransaction(page, { title: 'Salary', amount: '10000.10', type: 'income' })
  await addTransaction(page, { title: 'Groceries', amount: '250.25', notes: 'Fresh produce', category: 'groceries' })
  await addTransaction(page, { title: 'Last month bus', amount: '99.99', date: '2026-10-31', category: 'transport' })
  await addTransaction(page, { title: 'Foreign trip', amount: '40.00', currency: 'USD' })
  await expect(page.locator('.stat-value')).toHaveText(['₹10,000.10', '₹250.25', '₹9,749.85'])
  await expect(page.getByTestId('money-chart')).toBeVisible()
  await page.getByRole('tab', { name: 'Daily', exact: true }).click()
  await expect(page.locator('.stat-value').nth(1)).toHaveText('₹250.25')
  await page.getByRole('tab', { name: 'Yearly', exact: true }).click()
  await expect(page.locator('.stat-value').nth(1)).toHaveText('₹350.24')
  await page.getByRole('tab', { name: 'Monthly', exact: true }).click()
  await page.getByRole('tab', { name: 'Transactions', exact: true }).click()
  await page.getByRole('searchbox', { name: 'Search transactions…' }).fill('Fresh produce')
  await expect(page.getByTestId('transaction-row')).toHaveCount(1)
  await page.getByRole('button', { name: 'Edit: Groceries', exact: true }).click()
  await page.getByRole('dialog').getByLabel('Amount', { exact: true }).fill('275.75')
  await saveDialog(page, 'Save changes')
  await expect(page.locator('.stat-value')).toHaveText(['₹10,000.10', '₹275.75', '₹9,724.35'])
  await goto(page, '/settings')
  await page.getByLabel('Currency', { exact: true }).selectOption('USD')
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await goto(page, '/money')
  await expect(page.locator('.stat-value').nth(1)).toContainText('40.00')
  expect((await readWorkspace(page)).transactions.find(record => record.title === 'Groceries')?.currency).toBe('INR')
  await page.getByRole('tab', { name: 'Transactions', exact: true }).click()
  await page.getByRole('button', { name: 'Delete: Foreign trip', exact: true }).click()
  await confirmDelete(page)
  await goto(page, '/settings')
  await page.getByLabel('Currency', { exact: true }).selectOption('INR')
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await goto(page, '/money')
  await page.getByRole('tab', { name: 'Transactions', exact: true }).click()
  await page.getByLabel('Transaction dates', { exact: true }).selectOption('all')
  await expect(page.getByTestId('transaction-row')).toHaveCount(3)
  await page.getByRole('button', { name: 'Delete: Groceries', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByTestId('transaction-row')).toHaveCount(3)
  await page.getByRole('button', { name: 'Delete: Groceries', exact: true }).click()
  await confirmDelete(page)
  await page.reload()
  await expect(page.locator('.stat-value')).toHaveText(['₹10,000.10', '₹0.00', '₹10,000.10'])
  expect((await readWorkspace(page)).transactions).toHaveLength(2)
})

test('budgets and savings goals are editable, validated and calculated from records', async ({ page }) => {
  await goto(page, '/money')
  await addTransaction(page, { title: 'Groceries', amount: '250.25', category: 'groceries' })
  await page.getByRole('tab', { name: 'Budgets', exact: true }).click()
  await page.getByRole('button', { name: 'Set a budget', exact: true }).first().click()
  await page.getByRole('dialog').getByLabel('Amount', { exact: true }).fill('500')
  await saveDialog(page, 'Set a budget')
  await expect(page.locator('.budget-card')).toContainText('₹249.75 left')
  await page.getByRole('button', { name: 'Set a budget', exact: true }).click()
  await page.getByRole('dialog').getByLabel('Amount', { exact: true }).fill('500')
  await page.getByRole('dialog').getByRole('button', { name: 'Set a budget', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('A budget already exists')
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: 'Edit: Groceries', exact: true }).click()
  await page.getByRole('dialog').getByLabel('Amount', { exact: true }).fill('600')
  await saveDialog(page, 'Save changes')
  await expect(page.locator('.budget-card')).toContainText('₹349.75 left')
  await page.getByRole('tab', { name: 'Savings goals', exact: true }).click()
  await page.getByRole('button', { name: 'New savings goal', exact: true }).first().click()
  let dialog = page.getByRole('dialog')
  await dialog.getByLabel('Name', { exact: true }).fill('Holiday fund')
  await dialog.getByLabel('Target amount', { exact: true }).fill('5000')
  await dialog.getByLabel('Saved so far', { exact: true }).fill('1200')
  await dialog.getByLabel('Target date', { exact: true }).fill('2027-05-01')
  await saveDialog(page, 'New savings goal')
  await expect(page.locator('.goal-card').getByRole('progressbar')).toHaveAttribute('aria-valuenow', '24')
  await page.getByRole('button', { name: 'Edit: Holiday fund', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Saved so far', { exact: true }).fill('1500')
  await saveDialog(page, 'Save changes')
  await expect(page.locator('.goal-card').getByRole('progressbar')).toHaveAttribute('aria-valuenow', '30')
  await expect(page.locator('.stat-value').nth(1)).toHaveText('₹250.25')
  await page.getByRole('button', { name: 'Delete: Holiday fund', exact: true }).click()
  await confirmDelete(page)
  await page.getByRole('tab', { name: 'Budgets', exact: true }).click()
  await page.getByRole('button', { name: 'Delete: Groceries', exact: true }).click()
  await confirmDelete(page)
  const data = await readWorkspace(page)
  expect(data.budgets).toHaveLength(0)
  expect(data.savingsGoals).toHaveLength(0)
  expect(data.transactions).toHaveLength(1)
})
